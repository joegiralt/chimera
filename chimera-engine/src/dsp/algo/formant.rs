//! The formant grain's pure laws (spec § 3): the window `(4x(1 − x))^q`,
//! its SKIRT constants and curves. Those are measured on the host from the
//! window's definition (`formant_laws_test`'s `measure` and `print_curves`).

use super::math::{clampf, sqrt};

/// The carrier's level reference: −12 dB of a full-scale sine's RMS.
pub const R_REF: f32 = 0.251_19;

/// The floor under the exact-energy bracket `1 − ρ`.
pub const BRACKET_FLOOR: f32 = 0.05;

pub const NYQUIST_HZ: f32 = 24_000.0;

/// FC's floor.
pub(super) const FC_MIN: f32 = 20.0;

/// The width floor `B_min = K_3·f0/2`: SKIRT 3's span in two periods, the
/// same at every SKIRT.
pub fn width_floor(f0: f32) -> f32 {
    Skirt::S3.k() * f0 / 2.0
}

/// One lane's latched law (spec § 3): the band, the window, the gains and
/// the edge fade.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct FormantLaw {
    /// The carrier, Hz.
    pub fc: f32,
    /// The −3 dB full width, Hz.
    pub bw_eff: f32,
    /// The window's length, periods.
    pub d: f32,
    /// `2 − D`, periods.
    pub slack: f32,
    /// The modulator gain: the raw grain to a peak of 1.
    pub g_m: f32,
    /// The carrier gain: RMS at R, under the peak ceiling.
    pub g_c: f32,
    /// The gain fade where even `B_min` reaches past Nyquist.
    pub edge: f32,
}

/// The law at pitch `f0`, carrier `fc` and width `bw` (Hz).
pub fn formant_law(f0: f32, fc: f32, bw: f32, s: Skirt) -> FormantLaw {
    let b_min = width_floor(f0);
    let m = s.m_q();
    let room = (NYQUIST_HZ - fc) / m;
    let (fc, bw_eff, edge) = if room >= b_min {
        (fc, sqrt(bw * bw + b_min * b_min).min(room), 1.0)
    } else {
        let h = b_min / 2.0;
        let edge = clampf((room - h) / h, 0.0, 1.0);
        (fc.min(NYQUIST_HZ - m * h), b_min, edge)
    };
    let fc = fc.max(FC_MIN);
    let l = s.k() / bw_eff;
    let d = l * f0;
    let lanes = if d > 1.0 { 2.0 } else { 1.0 };
    let p_hat = (lane_peak(s, fc * l) * lanes).min(1.0);
    let bracket = (1.0 - rho(s, 2.0 * fc * l)).max(BRACKET_FLOOR);
    FormantLaw {
        fc,
        bw_eff,
        d,
        slack: 2.0 - d,
        g_m: 1.0 / p_hat,
        g_c: (R_REF / sqrt(d * s.c_q() * bracket)).min(1.0 / p_hat),
        edge,
    }
}

/// The window's exponent, `q = 2^(SKIRT+1)`: how steeply the skirts fall.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Skirt {
    S0,
    S1,
    S2,
    S3,
}

impl Skirt {
    pub const ALL: [Skirt; 4] = [Skirt::S0, Skirt::S1, Skirt::S2, Skirt::S3];

    /// A stored SKIRT, held to 0–3.
    pub const fn from_code(v: u8) -> Skirt {
        match v {
            0 => Skirt::S0,
            1 => Skirt::S1,
            2 => Skirt::S2,
            _ => Skirt::S3,
        }
    }

    pub const fn q(self) -> u32 {
        2 << self as u32
    }

    /// The span: the formant's −3 dB full width × the window's length.
    pub const fn k(self) -> f32 {
        [1.3748, 1.7341, 2.2910, 3.1208][self as usize]
    }

    /// The window's energy, the mean of `W²`:
    /// `4^(2q)·((2q)!)² / (4q + 1)!`.
    pub const fn c_q(self) -> f32 {
        [0.40635, 0.29954, 0.21653, 0.15486][self as usize]
    }

    /// The −60 dB upper extent from the centre, × BW_eff.
    pub const fn m_q(self) -> f32 {
        [5.528, 2.631, 2.078, 1.985][self as usize]
    }
}

/// `W(x) = (4x(1 − x))^q` on [0, 1], 0 outside (and for NaN).
#[inline]
pub fn window(x: f32, s: Skirt) -> f32 {
    if !(x > 0.0 && x < 1.0) {
        return 0.0;
    }
    let mut u = 4.0 * x * (1.0 - x);
    for _ in 0..=s as u32 {
        u *= u;
    }
    u
}

/// `ρ_q(ν)`, W²'s normalised transform at ν = 2·FC·L: the share of the
/// grain's energy its negative-frequency image cancels. 0 past ν = 12.
pub fn rho(s: Skirt, nu: f32) -> f32 {
    interp(&RHO[s as usize], nu, 0.0)
}

/// `p_q(FC·L)`, the single-lane peak of `W·sin` with the carrier centred;
/// never under the true peak, and 1.0 past FC·L = 16.
pub fn lane_peak(s: Skirt, fcl: f32) -> f32 {
    interp(&PEAK[s as usize], fcl, 1.0)
}

/// The tables' step, in their argument's units.
const NODE: f32 = 0.25;

/// `table` read linearly at `|x| / NODE`; `past` beyond its last node or
/// for NaN.
fn interp<const N: usize>(table: &[f32; N], x: f32, past: f32) -> f32 {
    let t = x.abs() / NODE;
    if t.is_nan() || t > (N - 1) as f32 {
        return past;
    }
    let i = (t as usize).min(N - 2);
    let f = t - i as f32;
    table[i] + (table[i + 1] - table[i]) * f
}

/// `x` cycles as a phase, `(x − ⌊x⌋)·2³²`, wrapping: for any finite `x`.
/// From 2²³ up every `f32` is whole, so it is 0 there (and for ±∞, NaN).
pub fn cycles_to_phase(x: f32) -> u32 {
    if !(x > -8_388_608.0 && x < 8_388_608.0) {
        return 0;
    }
    // |x| < 2²³: the truncation is exact, and so is `x − i`, in (−1, 1).
    let f = x - (x as i32) as f32;
    // |f·2³¹| ≤ 2³¹ − 128 < 2³¹: in i32's range.
    ((f * 2_147_483_648.0) as i32 as u32).wrapping_shl(1)
}

