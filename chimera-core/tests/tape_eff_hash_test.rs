//! TAPE's #793 loops, bit for bit as main played them (bc20ae7c): LOOP,
//! PING-PONG and TRON down to tiny loops (a wrap every few samples) with
//! and without fades, SCRUB, and STRETCH GRAIN, MONO and POLY forward and
//! reversed, short and long, held to their window's end. Each case's
//! output is hashed (FNV-1a over the bits) over a note, a release and its
//! tail.

mod common;

use core::mem::MaybeUninit;

use chimera_core::dsp::tape_engine::read::SourceView;
use chimera_core::dsp::tape_engine::{
    Direction, STRETCH_DEFAULTS, StretchKnobs, StretchType, TapeEngine, TapeEngineParams,
    TapeMachine, TapeModel, Tron,
};
use chimera_hal::BLOCK_SIZE;
use common::tape::{Mach, held_plain, saw_with_burst, sine};

const SR: u32 = 48_000;

fn fresh() -> TapeEngine {
    let mut slot = MaybeUninit::uninit();
    TapeEngine::init_in_place(&mut slot);
    // SAFETY: `init_in_place` wrote it whole.
    unsafe { slot.assume_init() }
}

/// `p(block)` from a note on `note`, released at block `off`, `blocks` in all.
fn hash(
    v: &SourceView<'_>,
    note: u8,
    p: &dyn Fn(usize) -> TapeEngineParams,
    off: usize,
    blocks: usize,
) -> u64 {
    let mut e = fresh();
    e.seed(3);
    e.note_on(note, &p(0), v, SR);
    let mut h = 0xcbf2_9ce4_8422_2325u64;
    let mut b = [0.0; BLOCK_SIZE];
    for n in 0..blocks {
        if n == off {
            e.note_off();
        }
        e.render(&mut b, &p(n), v, SR);
        for x in b {
            for byte in x.to_bits().to_le_bytes() {
                h = (h ^ u64::from(byte)).wrapping_mul(0x0100_0000_01b3);
            }
        }
    }
    h
}

fn stretch(kind: StretchType, length: f32, spray: f32, hold: bool) -> TapeEngineParams {
    let mut p = TapeEngineParams {
        machine: TapeMachine::Stretch,
        kind,
        motion: 0.5,
        root: 6_000.0,
        period: 48_000.0 / 261.625_58,
        ..TapeEngineParams::default()
    };
    p.stretch = StretchKnobs {
        length,
        grain: STRETCH_DEFAULTS.grain,
        spray,
        finish: if hold { 0.0 } else { 1.0 },
    };
    p
}

fn hashes() -> Vec<(String, u64)> {
    let sine_held = held_plain(&sine(48_000, 183.4, 48_000), 48_000);
    let saw_held = held_plain(&saw_with_burst(48_000, 1.5), 48_000);
    let sources = [
        ("sine", SourceView::new(&sine_held).unwrap()),
        ("saw", SourceView::new(&saw_held).unwrap()),
    ];
    let mut out = Vec::new();
    for (src, v) in &sources {
        let machines = [
            ("loop", Mach::fwd(TapeModel::Walk)),
            ("rev", Mach::rev(TapeModel::Walk)),
            ("ping", Mach::ping()),
        ];
        for (name, m) in machines {
            for size in [0.0, 0.02, 0.1, 0.4] {
                for xfade in [0.0, 0.1, 0.5] {
                    for tron in [Tron::Off, Tron::On] {
                        for note in [48u8, 60, 84] {
                            let p = m.params(TapeEngineParams {
                                size,
                                xfade,
                                tron,
                                motion: 0.3,
                                ..TapeEngineParams::default()
                            });
                            let h = hash(v, note, &|_| p, 150, 220);
                            out.push((format!("{src} {name} s{size} x{xfade} {tron:?} {note}"), h));
                        }
                    }
                }
            }
            // SIZE sweeping: the loop's length moves every block.
            let p = |n: usize| {
                m.params(TapeEngineParams {
                    size: 0.02 + 0.4 * (n as f32 / 300.0),
                    xfade: 0.1,
                    ..TapeEngineParams::default()
                })
            };
            out.push((format!("{src} {name} sweep"), hash(v, 60, &p, 250, 320)));
        }
        // LOOP still: MOTION 0.
        let p = Mach::fwd(TapeModel::Walk).params(TapeEngineParams {
            size: 0.05,
            xfade: 0.2,
            motion: 0.0,
            direction: Direction::Loop,
            ..TapeEngineParams::default()
        });
        out.push((format!("{src} loop still"), hash(v, 60, &|_| p, 150, 220)));
        // SCRUB, the finger moving.
        let p = |n: usize| {
            Mach::fwd(TapeModel::Scrub).params(TapeEngineParams {
                size: 0.05,
                xfade: 0.1,
                motion: 0.5 + 0.4 * ((n as f32) * 0.05).sin(),
                ..TapeEngineParams::default()
            })
        };
        out.push((format!("{src} scrub"), hash(v, 60, &p, 250, 320)));
        for kind in [StretchType::Grain, StretchType::Mono, StretchType::Poly] {
            for (length, spray, hold) in [
                (0.0, 0.0, true),
                (0.4, 0.7, true),
                (0.0, 0.3, false),
                (1.0, 0.0, false),
            ] {
                for rev in [false, true] {
                    for note in [48u8, 60, 72] {
                        let mut p = stretch(kind, length, spray, hold);
                        if rev {
                            (p.start, p.end) = (p.end, p.start);
                        }
                        let h = hash(v, note, &|_| p, 500, 600);
                        out.push((
                            format!("{src} {kind:?} l{length} sp{spray} h{hold} r{rev} {note}"),
                            h,
                        ));
                    }
                }
            }
        }
    }
    out
}

