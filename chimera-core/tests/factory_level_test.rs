fn block_rms(out: &[f32]) -> Vec<f32> {
    out.chunks(64)
        .step_by(8)
        .map(|b| (b.iter().map(|&x| x as f64 * x as f64).sum::<f64>() / 64.0).sqrt() as f32)
        .collect()
}

/// Sounds whose data can't restore the old render exactly (#192): the
/// largest per-block change allowed, in dB, just above the measured one.
/// MORPH PAD only, over this harness's first 0.53 s of its sweep (1.06 dB,
/// 1.12 through ADR 0060's blocker); `morph_pad_over_its_whole_lfo_sweep`
/// bounds the whole of it.
const KNOWN: [(usize, f32); 1] = [(6, 1.15)];

#[test]
fn factory_sounds_render_as_before_the_new_norm() {
    for (i, old) in OLD_RMS.iter().enumerate() {
        let now = block_rms(&render_case(Case::Factory(i as u8)));
        let known = KNOWN.iter().find(|k| k.0 == i).map(|k| k.1);
        for (k, (a, b)) in now.iter().zip(old).enumerate() {
            match known {
                None => assert!(
                    (a - b).abs() <= 1e-5,
                    "factory {i} block {}: {a} vs {b}",
                    8 * k
                ),
                Some(db) if *b > 1e-4 => {
                    let d = (20.0 * (a / b).log10()).abs();
                    assert!(d <= db, "factory {i} block {}: {d} dB", 8 * k);
                }
                Some(_) => assert!((a - b).abs() <= 1e-4, "factory {i} block {}", 8 * k),
            }
        }
    }
}

