"""Every published source file carries its copyright and licence header,
upstream authors' lines above ours; `just headers` writes them idempotently
(standard library only)."""

import importlib.util
import pathlib
import unittest

spec = importlib.util.spec_from_file_location("headers", pathlib.Path(__file__).with_name("headers.py"))
headers = importlib.util.module_from_spec(spec)
spec.loader.exec_module(headers)


class Tree(unittest.TestCase):
    def test_every_published_source_has_its_header(self):
        self.assertEqual(headers.missing(), [], "run `just headers`")

    def test_every_upstream_path_is_published(self):
        published = set(headers.published())
        self.assertEqual([p for p in headers.UPSTREAM if p not in published], [])

    def test_upstream_notices_are_kept(self):
        # An upstream file keeps its authors' own notice below the header.
        root = headers.ROOT
        for p in ("chimera-engine/src/dsp/modal/rings.rs", "chimera-engine/src/dsp/grain/core.rs"):
            text = (root / p).read_text(encoding="utf-8")
            self.assertIn("Emilie Gillet", text.split("SPDX-License-Identifier")[1], p)


class Apply(unittest.TestCase):
    SPDX = f"SPDX-License-Identifier: {headers.LICENCE}"

    def test_rust(self):
        got = headers.apply("a/b.rs", "//! Doc.\nfn f() {}\n")
        self.assertEqual(got, f"// {headers.OWNER}\n// {self.SPDX}\n\n//! Doc.\nfn f() {{}}\n")

    def test_idempotent(self):
        for path, text in (
            ("a/b.rs", "// own comment\nfn f() {}\n"),
            ("t.py", "#!/usr/bin/env python3\n\"\"\"Doc.\"\"\"\n"),
            ("m/memory.x", "MEMORY {}\n"),
            ("Justfile", "# Justfile\nx:\n    true\n"),
            ("chimera-engine/src/dsp/rev/room.rs", "//! ROOM.\n"),
        ):
            once = headers.apply(path, text)
            self.assertEqual(headers.apply(path, once), once, path)
            self.assertTrue(once.endswith(text.split("\n", 1)[-1] if text.startswith("#!") else text), path)

    def test_shebang_stays_first(self):
        got = headers.apply("t.sh", "#!/bin/sh\necho\n")
        self.assertTrue(got.startswith(f"#!/bin/sh\n# {headers.OWNER}\n# {self.SPDX}\n\necho"))

    def test_linker_script(self):
        got = headers.apply("m/memory.x", "MEMORY {}\n")
        self.assertTrue(got.startswith(f"/* {headers.OWNER} */\n/* {self.SPDX} */\n\nMEMORY"))

    def test_upstream_above_ours(self):
        got = headers.apply("chimera-engine/src/dsp/modal/rings.rs", "// Notice.\n").split("\n")
        self.assertEqual(got[0], "// " + headers.GILLET_RINGS)
        self.assertEqual(got[1:3], [f"// {headers.OWNER}", f"// {self.SPDX} AND MIT"])

    def test_a_new_constant_rewrites_the_header(self):
        old = headers.apply("a/b.rs", "fn f() {}\n")
        saved = headers.OWNER
        try:
            headers.OWNER = "Copyright (C) 2026 Someone Else"
            new = headers.apply("a/b.rs", old)
        finally:
            headers.OWNER = saved
        self.assertEqual(new, f"// Copyright (C) 2026 Someone Else\n// {self.SPDX}\n\nfn f() {{}}\n")

    def test_permissive_code_names_its_licence(self):
        got = headers.apply("chimera-engine/src/dsp/modal/rings.rs", "// Notice.\n").split("\n")
        self.assertEqual(got[2], f"// SPDX-License-Identifier: {headers.LICENCE} AND MIT")
        self.assertEqual(set(headers.EXTRA_LICENCE) - set(headers.UPSTREAM), set())

    def test_generated_is_exempt(self):
        text = "// @generated by a tool\nfn f() {}\n"
        self.assertEqual(headers.apply("a/g.rs", text), text)


if __name__ == "__main__":
    unittest.main()
